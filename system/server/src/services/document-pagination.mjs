export function buildDocumentPaginationScript() {
  return [
    '<script>',
    '(function () {',
    '  var PAGE_CONTENT_HEIGHT = 1046;',
    '  var PAGE_WIDTH = 794;',
    '',
    '  function ready(fn) {',
    '    if (document.readyState === "loading") {',
    '      document.addEventListener("DOMContentLoaded", fn, { once: true });',
    '      return;',
    '    }',
    '    fn();',
    '  }',
    '',
    '  function isTableBlock(node) {',
    '    return Boolean(node && node.matches && node.matches(".doc-section, .contract-section") && node.querySelector("table"));',
    '  }',
    '',
    '  function isKeepTogetherBlock(node) {',
    '    return Boolean(node && node.matches && node.matches(".doc-card, .doc-summary-grid, .contract-box, .contract-clause, .contract-signature-grid, .contract-signature-box"));',
    '  }',
    '',
    '  function measureHeight(node, sandbox) {',
    '    var clone = node.cloneNode(true);',
    '    sandbox.innerHTML = "";',
    '    sandbox.appendChild(clone);',
    '    return clone.offsetHeight;',
    '  }',
    '',
    '  function createSandbox() {',
    '    var sandbox = document.createElement("div");',
    '    sandbox.className = "document-pagination-sandbox";',
    '    document.body.appendChild(sandbox);',
    '    return sandbox;',
    '  }',
    '',
    '  function createPage() {',
    '    var page = document.createElement("section");',
    '    page.className = "document-page";',
    '    var inner = document.createElement("div");',
    '    inner.className = "document-page__inner";',
    '    page.appendChild(inner);',
    '    return { page: page, inner: inner };',
    '  }',
    '',
    '  function buildRowSplitBlocks(block) {',
    '    var table = block.querySelector("table");',
    '    if (!table) {',
    '      return [block.cloneNode(true)];',
    '    }',
    '',
    '    var heading = Array.from(block.children).find(function (child) {',
    '      return child !== table;',
    '    });',
    '    var thead = table.querySelector("thead");',
    '    var rows = Array.from(table.querySelectorAll("tbody tr"));',
    '    if (rows.length === 0) {',
    '      return [block.cloneNode(true)];',
    '    }',
    '',
    '    return rows.map(function (_, rowIndex) {',
    '      var nextBlock = block.cloneNode(false);',
    '      if (heading) {',
    '        nextBlock.appendChild(heading.cloneNode(true));',
    '      }',
    '      var nextTable = table.cloneNode(false);',
    '      if (thead) {',
    '        nextTable.appendChild(thead.cloneNode(true));',
    '      }',
    '      var body = document.createElement("tbody");',
    '      body.appendChild(rows[rowIndex].cloneNode(true));',
    '      nextTable.appendChild(body);',
    '      nextBlock.appendChild(nextTable);',
    '      nextBlock.setAttribute("data-table-fragment", "true");',
    '      return nextBlock;',
    '    });',
    '  }',
    '',
    '  function buildBlocks(root) {',
    '    var blocks = [];',
    '    Array.from(root.children).forEach(function (child) {',
    '      if (isTableBlock(child)) {',
    '        blocks = blocks.concat(buildRowSplitBlocks(child));',
    '        return;',
    '      }',
    '      blocks.push(child.cloneNode(true));',
    '    });',
    '    return blocks;',
    '  }',
    '',
    '  function paginateDocument() {',
    '    var shell = document.querySelector(".doc-shell, .contract-shell");',
    '    if (!shell) {',
    '      document.documentElement.classList.add("document-pagination-ready");',
    '      return;',
    '    }',
    '',
    '    var parent = shell.parentNode;',
    '    if (!parent) {',
    '      return;',
    '    }',
    '',
    '    var sandbox = createSandbox();',
    '    var blocks = buildBlocks(shell);',
    '    var wrapper = document.createElement("div");',
    '    wrapper.className = "document-pages";',
    '',
    '    var current = createPage();',
    '    wrapper.appendChild(current.page);',
    '',
    '    blocks.forEach(function (block) {',
    '      var blockHeight = measureHeight(block, sandbox);',
    '      var currentHeight = current.inner.scrollHeight;',
    '      var shouldMoveToNextPage = currentHeight > 0 && (currentHeight + blockHeight > PAGE_CONTENT_HEIGHT) && (isKeepTogetherBlock(block) || block.getAttribute("data-table-fragment") === "true");',
    '',
    '      if (shouldMoveToNextPage) {',
    '        current = createPage();',
    '        wrapper.appendChild(current.page);',
    '      }',
    '',
    '      current.inner.appendChild(block);',
    '',
    '      if (!shouldMoveToNextPage && current.inner.scrollHeight > PAGE_CONTENT_HEIGHT && current.inner.childElementCount > 1) {',
    '        current.inner.removeChild(block);',
    '        current = createPage();',
    '        wrapper.appendChild(current.page);',
    '        current.inner.appendChild(block);',
    '      }',
    '    });',
    '',
    '    parent.replaceChild(wrapper, shell);',
    '    sandbox.remove();',
    '    document.documentElement.classList.add("document-pagination-ready");',
    '  }',
    '',
    '  ready(function () {',
    '    paginateDocument();',
    '  });',
    '})();',
    '</script>',
  ].join('\n');
}

